"""Generate firmware/ow-epaper/secrets.h from the repo's .env (stdout).

    python firmware/ow-epaper/tools/gen_secrets.py > firmware/ow-epaper/secrets.h

Uses OW_ADDRESS and OW_UNLOCK_MAGIC, same as the Python tools. secrets.h is
gitignored — never commit it.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "src"))

MAC_RE = re.compile(r"^([0-9a-f]{2}:){5}[0-9a-f]{2}$")


def render(address: str, magic: bytes) -> str:
    addr = address.strip().lower()
    if not MAC_RE.match(addr):
        raise ValueError(f"OW_ADDRESS must look like AA:BB:CC:DD:EE:FF, got {address!r}")
    body = ", ".join(f"0x{b:02x}" for b in magic)
    return (
        "// Generated by tools/gen_secrets.py from .env — do not commit.\n"
        "#pragma once\n"
        "#include <cstdint>\n"
        f'#define OW_ADDRESS "{addr}"\n'
        f"#define OW_UNLOCK_MAGIC_LEN {len(magic)}\n"
        f"static const uint8_t OW_UNLOCK_MAGIC[OW_UNLOCK_MAGIC_LEN] = {{ {body} }};\n"
    )


def main() -> None:
    from ow_env import load_env, resolve_unlock_magic

    try:
        sys.stdout.write(render(load_env("OW_ADDRESS"), resolve_unlock_magic()))
    except ValueError as e:
        sys.exit(f"error: {e}")


if __name__ == "__main__":
    main()
